#!/usr/bin/env python3
"""
Local-only DDL transcription of option-c/schema.prisma, for --partial-postgres-only.

WHY THIS EXISTS
    The full G-3 driver generates its baseline with `prisma migrate diff`, which
    needs the Prisma schema engine. This sandbox cannot download it, so the
    PostgreSQL-level criteria (3, 4 and 5) could not be exercised locally at all.

    This script transcribes the reduced 10-model schema into the equivalent
    CREATE TABLE / ALTER TABLE ... FOREIGN KEY statements, so a developer can
    run the SQL-level controls against any disposable PostgreSQL.

WHAT THIS IS NOT
    * It is NOT the Prisma CLI and it does NOT reproduce Prisma's output.
    * It produces DDL that is *equivalent* for the columns these tests touch, so
      the constraints behave identically. It is not byte-comparable.
    * A run that uses it only ever reports criteria 1/2/4a/5b/6 as NOT TESTED.
      Such a run is local SQL evidence. It is never CI evidence and never a G-3
      pass. The CI workflow uses the real CLI.

Usage:  python3 baseline_ddl.py <schema.prisma> > baseline.sql
"""

import io
import re
import sys

SCALARS = {
    "String": "TEXT",
    "Int": "INTEGER",
    "Boolean": "BOOLEAN",
    "DateTime": "TIMESTAMP(3)",
    "Float": "DOUBLE PRECISION",
    "Decimal": "DECIMAL(65,30)",
}
DB_TYPES = {"Uuid": "UUID", "Text": "TEXT"}


def parse(path):
    models = []
    cur = None
    for raw in io.open(path, encoding="utf-8"):
        line = raw.strip()
        if not line or line.startswith("//"):
            continue
        m = re.match(r"^model\s+(\w+)\s*\{", line)
        if m:
            cur = {"name": m.group(1), "fields": [], "rels": [], "uniq": [],
                   "pks": [], "table": None}
            models.append(cur)
            continue
        if line == "}":
            cur = None
            continue
        if cur is None:
            continue
        m = re.match(r'^@@map\("(\w+)"\)', line)
        if m:
            cur["table"] = m.group(1)
            continue
        m = re.match(r'^@@unique\(\[([^\]]+)\](?:,\s*map:\s*"(\w+)")?\)', line)
        if m:
            cur["uniq"].append(([c.strip() for c in m.group(1).split(",")], m.group(2)))
            continue
        m = re.match(r"^@@id\(\[([^\]]+)\]\)", line)
        if m:
            cur["pks"].append([c.strip() for c in m.group(1).split(",")])
            continue
        if line.startswith("@@"):
            continue
        m = re.match(r"^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$", line)
        if not m:
            continue
        name, typ, _arr, opt, rest = m.groups()
        if typ not in SCALARS:
            cur["rels"].append({"type": typ, "attrs": rest})
            continue
        cur["fields"].append({"name": name, "type": typ, "null": bool(opt),
                              "attrs": rest})
    return models


def sql_type(field):
    m = re.search(r"@db\.(\w+)(?:\((\d+)\))?", field["attrs"])
    if not m:
        return SCALARS[field["type"]]
    base, size = m.group(1), m.group(2)
    if base in DB_TYPES:
        return DB_TYPES[base]
    if base == "VarChar":
        return "VARCHAR(%s)" % (size or 255)
    if base == "Char":
        return "CHAR(%s)" % (size or 1)
    return "TEXT"


def colname(field):
    m = re.search(r'@map\("(\w+)"\)', field["attrs"])
    return m.group(1) if m else field["name"]


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: baseline_ddl.py <schema.prisma>")
    models = parse(sys.argv[1])
    by_name = {m["name"]: m for m in models}

    def table_of(model_name):
        return by_name[model_name]["table"] or model_name

    def field_by_name(model, name):
        for f in model["fields"]:
            if f["name"] == name:
                return f
        raise KeyError("%s.%s" % (model["name"], name))

    out = [
        "-- =====================================================================",
        "-- LOCAL-ONLY DDL transcription of option-c/schema.prisma.",
        "-- Generated by baseline_ddl.py for --partial-postgres-only.",
        "-- This is NOT Prisma output and must never be presented as such.",
        "-- =====================================================================",
        "",
    ]

    for mo in models:
        table = table_of(mo["name"])
        defs = []
        for f in mo["fields"]:
            s = '  "%s" %s' % (colname(f), sql_type(f))
            if not f["null"]:
                s += " NOT NULL"
            if 'dbgenerated("gen_random_uuid()")' in f["attrs"]:
                s += " DEFAULT gen_random_uuid()"
            else:
                d = re.search(r'@default\("([^"]*)"\)|@default\(([A-Za-z0-9_.]+)\)',
                              f["attrs"])
                if d:
                    s += (" DEFAULT '%s'" % d.group(1)) if d.group(1) is not None \
                        else (" DEFAULT %s" % d.group(2))
            defs.append(s)

        for f in mo["fields"]:
            if "@id" in f["attrs"]:
                defs.append('  PRIMARY KEY ("%s")' % colname(f))
        for pk in mo["pks"]:
            cols = ", ".join('"%s"' % colname(field_by_name(mo, c)) for c in pk)
            defs.append("  PRIMARY KEY (%s)" % cols)
        for cols, name in mo["uniq"]:
            cc = ", ".join('"%s"' % colname(field_by_name(mo, c)) for c in cols)
            cname = name or "%s_%s_key" % (table, "_".join(cols))
            defs.append('  CONSTRAINT "%s" UNIQUE (%s)' % (cname, cc))
        for f in mo["fields"]:
            if "@unique" in f["attrs"]:
                defs.append('  CONSTRAINT "%s_%s_key" UNIQUE ("%s")'
                            % (table, colname(f), colname(f)))

        out.append('CREATE TABLE "%s" (\n%s\n);' % (table, ",\n".join(defs)))

    out.append("")

    # Referenced targets: a field that is the single-column primary key, or a
    # column of a composite primary key, is addressable by name.
    for mo in models:
        table = table_of(mo["name"])
        for rel in mo["rels"]:
            m = re.search(r"@relation\(fields: \[(\w+)\], references: \[(\w+)\]",
                          rel["attrs"])
            if not m:
                continue
            fld = field_by_name(mo, m.group(1))
            ref_model = by_name.get(rel["type"])
            if ref_model is None:
                sys.exit("unresolved relation target %s" % rel["type"])
            ref_fld = field_by_name(ref_model, m.group(2))
            delete = re.search(r"onDelete: (\w+)", rel["attrs"])
            update = re.search(r"onUpdate: (\w+)", rel["attrs"])
            out.append(
                'ALTER TABLE "%s" ADD CONSTRAINT "%s_%s_fkey" FOREIGN KEY ("%s") '
                'REFERENCES "%s" ("%s") ON DELETE %s ON UPDATE %s;'
                % (table, table, colname(fld), colname(fld),
                   table_of(ref_model["name"]), colname(ref_fld),
                   (delete.group(1).upper() if delete else "NO ACTION"),
                   (update.group(1).upper() if update else "NO ACTION")))

    out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
