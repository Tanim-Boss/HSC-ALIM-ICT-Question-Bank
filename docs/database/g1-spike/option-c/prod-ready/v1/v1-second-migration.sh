#!/usr/bin/env bash
# =====================================================================
# V-1 — THE REAL SECOND MIGRATION, THROUGH THE APPROVED OPTION C WORKFLOW
#
# V-1 is the highest-priority production-readiness check, because every G-3
# run so far exercised migration 0001 plus synthetic constrained-column
# changes applied with `psql`. The path the team will use EVERY WEEK — author
# migration 0002 from a snapshot-to-snapshot diff, review it, guard it, deploy
# it, prove the five protected FKs survived — had never been exercised on
# this repository. This driver exercises it.
#
# THE CHANGE IS REAL, NOT DECORATIVE
#   `questions` §3.3.7 records an "Optional, not proposed for 0001:
#   (created_at DESC) for 'recently added' admin list". Migration 0002 adds
#   exactly that index. It is:
#     * additive (an index; no column, no row, no constraint touched)
#     * a documented PROPOSAL that was deliberately deferred, not an invention
#     * provably non-destructive to C-1..C-5 (it does not mention them)
#   It does not change the approved 18-table physical design.
#
# THE WORKFLOW, STEP BY STEP (Option C, §11.4.3)
#   1. snapshots/prev.prisma  <- the datamodel as of migration 0001
#   2. add the index to a COPY of the datamodel (never the repo file)
#   3. `prisma migrate diff --from-schema prev --to-schema next --script`
#      -> the migration SQL, generated by Prisma, not by hand
#   4. assert the generated SQL contains NO DROP CONSTRAINT and no mention
#      of the five protected FKs  (this is the point of the whole workflow)
#   5. `guard.py sql` accepts it
#   6. `prisma migrate deploy` applies it to a database already at 0001
#   7. `migrate status` is clean; history and checksums verified
#   8. the five composite FKs are still present and still ENFORCING
#   9. the index actually exists and is used
#  10. a fresh database replays 0001 + 0002 to the identical shape
#
# NOTHING in prisma/migrations/ is created or modified by this driver: the
# candidate migration is written under a temporary output directory, so a
# failing run cannot leave a half-authored migration in the repository.
# Promoting it to a committed 0002 is a separate, reviewed act.
# =====================================================================
#   ./v1-second-migration.sh --url <db at 0001> --shadow-url <empty> \
#                            --replay-url <empty> [--out DIR]
# =====================================================================
set -Eeuo pipefail

V1_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# prod-ready/v1 -> two ups is option-c, three is g1-spike. The first draft used
# three, so GUARD and repo-guard.sh resolved to non-existent paths and the
# driver failed on its first CI run. Both are asserted below.
OC_DIR="$(cd "$V1_DIR/../.." && pwd)"             # .../option-c
# prod-ready/v1 -> five ups from the script dir is the repo root; verified by
# the prisma/ presence check because an off-by-one silently reads docs/.
REPO_ROOT="$(cd "$V1_DIR/../../../../../.." && pwd)"
[ -d "$REPO_ROOT/prisma" ] || { printf '[V1] FAIL: REPO_ROOT %s is not the repository root\n' "$REPO_ROOT" >&2; exit 1; }
PSQL="${PSQL:-psql}"
PRISMA_BIN="$REPO_ROOT/node_modules/.bin/prisma"
GUARD="$OC_DIR/guard.py"
PROD_SCHEMA="$REPO_ROOT/prisma/schema.prisma"
MIG_0001="$REPO_ROOT/prisma/migrations/0001_phase04a_question_bank/migration.sql"

URL=""; SHADOW=""; REPLAY=""; OUT_DIR="${OUT_DIR:-/tmp/v1-out}"; DRY="${V1_DRY:-0}"
usage() { printf 'usage: v1-second-migration.sh --url U --shadow-url S --replay-url R [--out D]\n' >&2; exit 2; }
while [ $# -gt 0 ]; do
  case "$1" in
    --url) URL="${2:-}"; shift 2 ;;
    --shadow-url) SHADOW="${2:-}"; shift 2 ;;
    --replay-url) REPLAY="${2:-}"; shift 2 ;;
    --out) OUT_DIR="${2:-}"; shift 2 ;;
    -h|--help) usage ;;
    *) printf 'unknown argument: %s\n' "$1" >&2; usage ;;
  esac
done
[ -n "$URL" ] && [ -n "$SHADOW" ] && [ -n "$REPLAY" ] || usage
mkdir -p "$OUT_DIR"
# The session directory MUST live inside the repository.
# `prisma.config.ts` does `import { defineConfig } from 'prisma/config'`, and Node
# resolves that specifier by walking UP from the config file's own location. A
# session directory under /tmp therefore cannot see the repo's node_modules and
# fails with "Cannot find module 'prisma/config'". This was the second V-1 CI
# failure: the paths were right, the config location was not.
mkdir -p "$REPO_ROOT/.v1-session"
SESS="$(mktemp -d "$REPO_ROOT/.v1-session/run.XXXXXX")"
cleanup() { rm -rf "$SESS"; rmdir "$REPO_ROOT/.v1-session" 2>/dev/null || true; }
trap cleanup EXIT

# A `set -e` abort produces no FAIL line, which made the first two CI failures
# visible only as "exit code 1". This trap names the exact command and line, and
# emits it as a GitHub annotation so the cause survives log-retention problems.
# Defined once so the trap can be lifted around intentionally-failing statements
# and then re-armed, without duplicating the trap body.
arm_err_trap() {
  trap 'printf "  ABORT  line %s: %s\n" "$LINENO" "$BASH_COMMAND" >&2;
        if [ -n "${GITHUB_ACTIONS:-}" ]; then
          printf "::error title=V-1 aborted::line %s: %s\n" "$LINENO" "$(printf "%s" "$BASH_COMMAND" | tr "\n" " " | cut -c1-400)" >&2
        fi' ERR
}
arm_err_trap

FAILS=0
pass() { printf '  PASS  %s\n' "$*"; }
fail() { printf '  FAIL  %s\n' "$*"; FAILS=$((FAILS+1)); }
info() { printf '  ....  %s\n' "$*"; }
head2() { printf '\n=== %s ===\n' "$*"; }
q() { "$PSQL" "${1:-$URL}" -Atq -v ON_ERROR_STOP=1 -c "$2"; }
# V1_DRY=1 exercises every non-Prisma step and PRINTS the Prisma commands
# instead of running them. The Prisma engine cannot be downloaded in some
# sandboxes, so this is how the surrounding shell logic is verified locally;
# CI runs the real thing. A DRY run is never reported as a V-1 pass.
prisma_run() {
  if [ "$DRY" = "1" ]; then
    printf '  DRY   would run: prisma %s\n' "$*" >&2
    return 0
  fi
  ( cd "$REPO_ROOT" && V1_DB="$URL" V1_SHADOW="$SHADOW" "$PRISMA_BIN" "$@" )
}

# Two config shapes on purpose:
#   mk_config      -> with a datasource, for `migrate deploy` / `migrate status`
#   mk_diff_config -> WITHOUT one, for `migrate diff --from-schema --to-schema`,
#                     which compares two files and needs no database at all.
# Declaring a datasource for the diff would make it depend on connectivity it
# does not use, and would fail confusingly if the URL were wrong.
mk_config() { # <schema> <config>
  cat > "$2" <<CFG
import { defineConfig } from 'prisma/config';
export default defineConfig({
  schema: '$1',
  migrations: { path: '$SESS/migrations' },
  datasource: {
    url: process.env.V1_DB,
    shadowDatabaseUrl: process.env.V1_SHADOW,
  },
});
CFG
}

mk_diff_config() { # <schema> <config>
  cat > "$2" <<CFG
import { defineConfig } from 'prisma/config';
export default defineConfig({
  schema: '$1',
});
CFG
}

# =====================================================================
head2 "0. preconditions — the database must already be at 0001"
# =====================================================================
[ -x "$PRISMA_BIN" ] || { printf '[V-1] FAIL: prisma CLI not found at %s\n' "$PRISMA_BIN" >&2; exit 1; }
# Assert every path the driver depends on, so a wrong relative path fails with a
# clear message instead of surfacing later as a confusing command-not-found.
for f in "$GUARD" "$OC_DIR/repo-guard.sh" "$PROD_SCHEMA" "$MIG_0001"; do
  [ -f "$f" ] || { printf '[V-1] FAIL: required file missing: %s\n' "$f" >&2; exit 1; }
done
printf '[V-1] paths resolved: OC_DIR=%s REPO_ROOT=%s\n' "$OC_DIR" "$REPO_ROOT"
pass "pinned Prisma CLI present ($(node -p "require('$REPO_ROOT/node_modules/prisma/package.json').version"))"

tabs="$(q "$URL" "SELECT count(*) FROM pg_tables WHERE schemaname='public' AND tablename<>'_prisma_migrations';")"
[ "$tabs" = "18" ] || { printf '[V-1] FAIL: primary DB has %s tables, expected the 18-table 0001 schema\n' "$tabs" >&2; exit 1; }
pass "primary database is at migration 0001 (18 tables)"

applied="$(q "$URL" "SELECT count(*) FROM _prisma_migrations WHERE finished_at IS NOT NULL AND rolled_back_at IS NULL;")"
[ "$applied" = "1" ] || { printf '[V-1] FAIL: expected exactly 1 applied migration before 0002, found %s\n' "$applied" >&2; exit 1; }
pass "exactly one applied migration in _prisma_migrations"

# the migration directory this driver builds contains ONLY 0001, so that
# generating 0002 cannot see or disturb anything else
mkdir -p "$SESS/migrations/0001_phase04a_question_bank"
cp "$MIG_0001" "$SESS/migrations/0001_phase04a_question_bank/migration.sql"
printf 'provider = "postgresql"\n' > "$SESS/migrations/migration_lock.toml"

# =====================================================================
head2 "1. snapshot the datamodel as of 0001  (snapshots/prev.prisma)"
# =====================================================================
cp "$PROD_SCHEMA" "$SESS/prev.prisma"
pass "prev.prisma captured from the committed prisma/schema.prisma"

# =====================================================================
head2 "2. apply the ONE additive change to a COPY of the datamodel"
# =====================================================================
# §3.3.7: "Optional, not proposed for 0001: (created_at DESC) for 'recently
# added' admin list". Prisma's index sort argument expresses DESC.
python3 - "$SESS/prev.prisma" "$SESS/next.prisma" <<'PY'
import io, sys
src, dst = sys.argv[1], sys.argv[2]
s = io.open(src, encoding='utf-8').read()
anchor = '  @@index([status, type, difficulty], map: "ix_questions_status_type_difficulty")'
assert anchor in s, "anchor for the questions index block not found"
addition = (anchor + '\n'
            '  /// V-1 change: the "recently added" admin listing index that §3.3.7\n'
            '  /// records as optional and deliberately NOT part of migration 0001.\n'
            '  @@index([createdAt(sort: Desc)], map: "ix_questions_created_at_desc")')
io.open(dst, 'w', encoding='utf-8').write(s.replace(anchor, addition, 1))
print("next.prisma written with ix_questions_created_at_desc")
PY
pass "next.prisma = prev.prisma + one index (§3.3.7's deferred 'recently added' index)"

diff <(sed 's/[[:space:]]*$//' "$SESS/prev.prisma") <(sed 's/[[:space:]]*$//' "$SESS/next.prisma") > "$OUT_DIR/02-datamodel-diff.txt" || true
info "the datamodel delta is $(grep -c '^>' "$OUT_DIR/02-datamodel-diff.txt" ) line(s):"
grep '^>' "$OUT_DIR/02-datamodel-diff.txt" | sed 's/^>/    /' || true

# =====================================================================
head2 "3. GENERATE the migration with a snapshot-to-snapshot diff"
# =====================================================================
# NOTE: the config file must be written BEFORE the command that consumes it.
# The first draft wrote it after, which would have failed in CI.
mk_diff_config "$SESS/next.prisma" "$SESS/diff.config.ts"
info "command: prisma migrate diff --from-schema prev.prisma --to-schema next.prisma --script"
set +e
prisma_run migrate diff \
  --from-schema "$SESS/prev.prisma" \
  --to-schema   "$SESS/next.prisma" \
  --script --config "$SESS/diff.config.ts" > "$OUT_DIR/03-generated.sql" 2> "$OUT_DIR/03-generated.err"
rc=$?
set -e
if [ $rc -ne 0 ]; then cat "$OUT_DIR/03-generated.err"; fail "migrate diff failed (exit $rc)"; fi
cat "$OUT_DIR/03-generated.sql"
[ -s "$OUT_DIR/03-generated.sql" ] || fail "the generated migration is EMPTY — the diff saw no change"
grep -qi "CREATE INDEX" "$OUT_DIR/03-generated.sql" \
  && pass "the generated migration creates an index (the change was seen, so the check is not vacuous)" \
  || fail "no CREATE INDEX in the generated migration"
grep -qi "ix_questions_created_at_desc" "$OUT_DIR/03-generated.sql" \
  && pass "the index is named as the datamodel declares it" \
  || fail "the expected index name is absent"

# =====================================================================
head2 "4. the generated migration must NOT touch C-1..C-5"
# =====================================================================
# This is the entire justification for Option C, asserted on real output.
if grep -qi "DROP CONSTRAINT" "$OUT_DIR/03-generated.sql"; then
  fail "the generated migration contains DROP CONSTRAINT"
else
  pass "zero DROP CONSTRAINT statements"
fi
if grep -qiE "fk_questions_(level_subject|chapter_subject|topic_chapter|subtopic_topic)|fk_answer_keys_options_of_version" "$OUT_DIR/03-generated.sql"; then
  fail "the generated migration mentions a protected composite FK"
else
  pass "no mention of any of the five protected composite FKs"
fi
if grep -qiE "^\s*(DROP TABLE|ALTER TABLE .* DROP COLUMN|TRUNCATE)" "$OUT_DIR/03-generated.sql"; then
  fail "the generated migration is destructive"
else
  pass "no DROP TABLE, no DROP COLUMN, no TRUNCATE"
fi

# =====================================================================
head2 "5. the migration passes the pre-deployment guards"
# =====================================================================
if python3 "$GUARD" sql "$OUT_DIR/03-generated.sql" > "$OUT_DIR/05-guard.log" 2>&1; then
  pass "guard.py sql accepts the generated migration (no false positive)"
else
  cat "$OUT_DIR/05-guard.log"; fail "guard.py sql rejected a legitimate additive migration"
fi
if bash "$OC_DIR/repo-guard.sh" "$REPO_ROOT" > "$OUT_DIR/05-repo-guard.log" 2>&1; then
  pass "the repository guard is clean"
else
  cat "$OUT_DIR/05-repo-guard.log"; fail "the repository guard reports a violation"
fi

# =====================================================================
head2 "6. DEPLOY 0002 with prisma migrate deploy"
# =====================================================================
mkdir -p "$SESS/migrations/0002_v1_recently_added_index"
cp "$OUT_DIR/03-generated.sql" "$SESS/migrations/0002_v1_recently_added_index/migration.sql"
mk_config "$SESS/next.prisma" "$SESS/deploy.config.ts"

# the primary DB is at 0001 already, so deploy has exactly one new migration
set +e
prisma_run migrate deploy --config "$SESS/deploy.config.ts" > "$OUT_DIR/06-deploy.log" 2>&1
rc=$?
set -e
cat "$OUT_DIR/06-deploy.log"
[ $rc -eq 0 ] || fail "migrate deploy of 0002 failed (exit $rc)"
[ $rc -eq 0 ] && pass "migration 0002 applied through prisma migrate deploy"

# =====================================================================
head2 "7. history and checksums"
# =====================================================================
set +e
prisma_run migrate status --config "$SESS/deploy.config.ts" > "$OUT_DIR/07-status.log" 2>&1
rc=$?
set -e
cat "$OUT_DIR/07-status.log"
[ $rc -eq 0 ] && pass "'migrate status' is clean after deploying 0002" || fail "'migrate status' is not clean (exit $rc)"

applied2="$(q "$URL" "SELECT count(*) FROM _prisma_migrations WHERE finished_at IS NOT NULL AND rolled_back_at IS NULL;")"
[ "$applied2" = "2" ] && pass "two applied migrations now recorded" || fail "expected 2 applied migrations, found $applied2"

unfinished="$(q "$URL" "SELECT count(*) FROM _prisma_migrations WHERE finished_at IS NULL AND rolled_back_at IS NULL;")"
[ "$unfinished" = "0" ] && pass "no unfinished migration" || fail "$unfinished unfinished migration(s)"

q "$URL" "SELECT coalesce(json_agg(row_to_json(t)),'[]'::json) FROM (SELECT migration_name, checksum FROM _prisma_migrations WHERE finished_at IS NOT NULL AND rolled_back_at IS NULL) t;" > "$OUT_DIR/07-history.json"
if python3 "$GUARD" history "$OUT_DIR/07-history.json" "$SESS/migrations" > "$OUT_DIR/07-history.log" 2>&1; then
  cat "$OUT_DIR/07-history.log"
  pass "the checksum control passes on both migrations"
else
  cat "$OUT_DIR/07-history.log"; fail "the checksum control failed after 0002"
fi

# =====================================================================
head2 "8. the five protected FKs SURVIVED and still ENFORCE"
# =====================================================================
Q="$(python3 -c "import sys;sys.path.insert(0,'$OC_DIR');import guard;print(guard.CATALOG_QUERY)")"
q "$URL" "SELECT coalesce(json_agg(row_to_json(t)),'[]'::json) FROM ($Q) t;" > "$OUT_DIR/08-catalog.json"
if python3 "$GUARD" catalog "$OUT_DIR/08-catalog.json" > "$OUT_DIR/08-catalog.log" 2>&1; then
  cat "$OUT_DIR/08-catalog.log"
  pass "all five composite FKs present with approved columns and actions after 0002"
else
  cat "$OUT_DIR/08-catalog.log"; fail "a protected composite FK was altered or lost by 0002"
fi

# presence is not enforcement: force a C-5 violation and require rejection.
# A bare `INSERT ... SELECT ... LIMIT 1` against an empty table reports
# "INSERT 0 0" and proves nothing, so build the fixture on purpose and first
# assert the fixture row actually exists (a positive control): a valid key must
# be ACCEPTED. Only then is a rejection meaningful.
FIX="$(q "$URL" "SELECT gen_random_uuid()::text")"
QF="$(q "$URL" "SELECT gen_random_uuid()::text")"
QQ="$(q "$URL" "SELECT gen_random_uuid()::text")"
QV="$(q "$URL" "SELECT gen_random_uuid()::text")"
QO="$(q "$URL" "SELECT gen_random_uuid()::text")"
QK="$(q "$URL" "SELECT gen_random_uuid()::text")"
# subjects is a global table (no education_level_id) — checked against 0001
if {
  q "$URL" "INSERT INTO education_levels (id, code, name_bn, name_en, created_at, updated_at)
    VALUES ('$FIX', 'V1FIX', 'V1FIX', 'V1FIX', now(), now());"
  q "$URL" "INSERT INTO subjects (id, code, name_bn, name_en, created_at, updated_at)
    VALUES ('$QF', 'V1FIXSUB', 'V1FIX', 'V1FIX', now(), now());"
  # C-1 (fk_questions_level_subject) requires the level/subject pair to exist
  q "$URL" "INSERT INTO level_subjects (level_id, subject_id, created_at)
    VALUES ('$FIX', '$QF', now());"
  q "$URL" "INSERT INTO questions (id, type, status, difficulty, created_via, education_level_id, subject_id, marks, created_at, updated_at)
    VALUES ('$QQ', 'MCQ', 'DRAFT', 'MEDIUM', 'MANUAL', '$FIX', '$QF', 1, now(), now());"
  q "$URL" "INSERT INTO question_versions (id, question_id, version_number, status, content, created_at, updated_at)
    VALUES ('$QV', '$QQ', 1, 'DRAFT', '{\"format\":1,\"version\":1,\"blocks\":[]}'::jsonb, now(), now());"
  q "$URL" "INSERT INTO question_options (id, version_id, key, content, sort_order, created_at)
    VALUES ('$QO', '$QV', 'A', '{}'::jsonb, 0, now());"
  # positive control: the fixture is well-formed, so a VALID key is ACCEPTED
  q "$URL" "INSERT INTO answer_keys (id, version_id, mcq_correct_option_key, is_verified, created_at, updated_at)
    VALUES ('$QK', '$QV', 'A', false, now(), now());"
} >/dev/null 2>&1; then
  pass "fixture built, and a VALID key was ACCEPTED (so the rejection below is meaningful)"
  # Remove the control row again. answer_keys has a unique version_id
  # (uq_answer_keys_version), so leaving it in place would make the negative
  # probe fail on uniqueness instead of on C-5 — passing for the wrong reason.
  q "$URL" "DELETE FROM answer_keys WHERE id='$QK';" >/dev/null 2>&1 || true
  gone="$(q "$URL" "SELECT count(*) FROM answer_keys WHERE version_id='$QV';")"
  [ "$gone" = "0" ] && pass "control row removed — the next insert can only fail on C-5" \
                    || fail "control row still present ($gone); the negative probe would be ambiguous"
else
  printf '  fixture rows present: %s\n' "$(q "$URL" "SELECT (SELECT count(*) FROM answer_keys WHERE version_id='$QV')||'/'||(SELECT count(*) FROM question_options WHERE version_id='$QV')")"
  fail "could not build the C-5 fixture — the enforcement check cannot be trusted"
fi

# The rejection below is EXPECTED, so the ERR trap must be lifted around it:
# `set +e` disables errexit but the ERR trap still fires on any failing command,
# which would emit a misleading "V-1 aborted" annotation in CI for a passing check.
trap - ERR
set +e
out="$("$PSQL" "$URL" -v ON_ERROR_STOP=0 -c "
INSERT INTO answer_keys (id, version_id, mcq_correct_option_key, is_verified, created_at, updated_at)
VALUES (gen_random_uuid(), '$QV', 'Z', false, now(), now());" 2>&1)"
set -e
arm_err_trap
if printf '%s' "$out" | grep -qE "fk_answer_keys_options_of_version|ck_question_options|ck_answer_keys"; then
  pass "C-5 still rejects an invalid key AFTER 0002 (constraints are enforcing, not just present)"
else
  printf '%s\n' "$out"; fail "C-5 did not reject an invalid key after 0002"
fi
# tear the fixture down again: this driver must not contaminate what it verifies
{
  q "$URL" "DELETE FROM answer_keys WHERE version_id='$QV';"
  q "$URL" "DELETE FROM question_options WHERE version_id='$QV';"
  q "$URL" "DELETE FROM question_versions WHERE id='$QV';"
  q "$URL" "DELETE FROM questions WHERE id='$QQ';"
  q "$URL" "DELETE FROM level_subjects WHERE level_id='$FIX' AND subject_id='$QF';"
  q "$URL" "DELETE FROM subjects WHERE id='$QF';"
  q "$URL" "DELETE FROM education_levels WHERE id='$FIX';"
} >/dev/null 2>&1 || true
left="$(q "$URL" "SELECT (SELECT count(*) FROM questions)+(SELECT count(*) FROM answer_keys)+(SELECT count(*) FROM education_levels WHERE code='V1FIX');")"
[ "$left" = "0" ] && pass "fixture removed; the database is left as it was found" \
                  || fail "fixture cleanup left $left row(s) behind"

# =====================================================================
head2 "9. the change took effect: the index exists and is used"
# =====================================================================
IDEF="$(q "$URL" "SELECT indexdef FROM pg_indexes WHERE indexname='ix_questions_created_at_desc';")"
info "$IDEF"
case "$IDEF" in
  *"created_at"*DESC*) pass "the descending index exists on questions(created_at DESC)" ;;
  *) fail "the descending index is absent or wrong: $IDEF" ;;
esac

# An index can exist and still be unusable (left invalid by a failed CREATE
# INDEX CONCURRENTLY, or not ready). Check the catalog flags directly — this does
# not depend on table statistics, unlike the planner check that follows.
IOSTAT="$(q "$URL" "SELECT i.indisvalid||'/'||i.indisready||'/'||i.indislive
  FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid
  WHERE c.relname='ix_questions_created_at_desc';")"
[ "$IOSTAT" = "true/true/true" ] && pass "the index is valid, ready and live (indisvalid/indisready/indislive)" \
  || fail "the index exists but is not fully usable: $IOSTAT"

# An index that exists but is never chosen is not really usable; confirm the
# planner can use it for the "recently added" shape with seqscan disabled.
# This is ADVISORY only: on an empty table the planner legitimately prefers a
# sequential scan even when enable_seqscan is off, so it must not fail the run.
q "$URL" "SET enable_seqscan = off; EXPLAIN SELECT id FROM questions ORDER BY created_at DESC LIMIT 20;" 2>/dev/null > "$OUT_DIR/09-plan.txt" || true
if grep -qi "ix_questions_created_at_desc" "$OUT_DIR/09-plan.txt"; then
  pass "the planner uses ix_questions_created_at_desc for the 'recently added' query"
else
  cat "$OUT_DIR/09-plan.txt"; info "planner did not pick the index on an empty/small table — see below"
fi

# inventory must be otherwise unchanged: +1 index, everything else identical
inv="$(q "$URL" "SELECT (SELECT count(*) FROM pg_tables WHERE schemaname='public' AND tablename<>'_prisma_migrations')
   ||'/'||(SELECT count(*) FROM pg_type WHERE typtype='e' AND typnamespace='public'::regnamespace)
   ||'/'||(SELECT count(*) FROM pg_constraint WHERE contype='f' AND connamespace='public'::regnamespace)
   ||'/'||(SELECT count(*) FROM pg_constraint WHERE contype='c' AND connamespace='public'::regnamespace AND conname LIKE 'ck\_%');")"
[ "$inv" = "18/7/26/47" ] && pass "inventory unchanged by 0002: 18/7/26/47" || fail "inventory changed: $inv (expected 18/7/26/47)"

# =====================================================================
head2 "10. REPRODUCIBILITY — 0001 + 0002 replay to the same shape"
# =====================================================================
objs="$(q "$REPLAY" "SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relkind IN ('r','p','i','S','v','m');")"
if [ "$objs" != "0" ]; then
  fail "the replay database is not empty ($objs objects)"
else
  mk_config "$SESS/next.prisma" "$SESS/replay.config.ts"
  ( cd "$REPO_ROOT" && V1_DB="$REPLAY" V1_SHADOW="$SHADOW" "$PRISMA_BIN" migrate deploy --config "$SESS/replay.config.ts" ) > "$OUT_DIR/10-replay.log" 2>&1 \
    || { cat "$OUT_DIR/10-replay.log"; fail "replay deploy failed"; }
  rinv="$(q "$REPLAY" "SELECT (SELECT count(*) FROM pg_tables WHERE schemaname='public' AND tablename<>'_prisma_migrations')
     ||'/'||(SELECT count(*) FROM pg_type WHERE typtype='e' AND typnamespace='public'::regnamespace)
     ||'/'||(SELECT count(*) FROM pg_constraint WHERE contype='f' AND connamespace='public'::regnamespace)
     ||'/'||(SELECT count(*) FROM pg_constraint WHERE contype='c' AND connamespace='public'::regnamespace AND conname LIKE 'ck\_%');")"
